// Runs after `quartz build`: writes public/version.json, public/sw.js and public/_headers.
//
// Two different hashes, on purpose:
//  - the DOCUMENTS version hashes site/content (the topics), so it moves exactly when a
//    document is added, edited or removed. That is what the footer shows.
//  - the CACHE key hashes every file the service worker precaches (pages, CSS, JS, the
//    topic index), but not the build date. A rebuild that changes nothing therefore yields a
//    byte-identical sw.js and the browser offers no "Update"; any real change yields a new
//    one. Hashing the build date in would prompt an update on every deploy.
import { createHash } from "node:crypto"
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs"
import { join, relative, sep } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(fileURLToPath(import.meta.url), "..", "..")
const contentDir = join(root, "..", "content")
const publicDir = join(root, "public")

function walk(dir) {
  const out = []
  for (const name of readdirSync(dir).sort()) {
    const p = join(dir, name)
    if (statSync(p).isDirectory()) out.push(...walk(p))
    else out.push(p)
  }
  return out
}
const rel = (base, p) => relative(base, p).split(sep).join("/")
const sha = (h) => h.digest("hex")

// Obsidian metadata and OS junk are not documents.
const isDocument = (r) =>
  !r.split("/").some((s) => s.startsWith("_") || s === ".obsidian" || s === ".git" || s === ".DS_Store")
const docs = walk(contentDir)
  .map((p) => rel(contentDir, p))
  .filter(isDocument)
if (docs.length === 0) {
  console.error("postbuild: no documents found in", contentDir)
  process.exit(2)
}
// Topics-v4.zip shipped five 0-byte files that went live as blank pages; refuse to build that again.
const empty = docs.filter((r) => statSync(join(contentDir, r)).size === 0)
if (empty.length) {
  console.error("postbuild: empty topic files:\n  " + empty.join("\n  "))
  process.exit(1)
}
const contentHash = createHash("sha256")
for (const r of docs)
  contentHash
    .update(r + "\0")
    .update(readFileSync(join(contentDir, r)))
    .update("\0")
const content = sha(contentHash).slice(0, 8)

// sitemap and RSS carry build dates, sw.js and version.json are generated here, _headers is
// not content. Everything else is part of the offline copy.
const SKIP = new Set(["sw.js", "version.json", "_headers", "sitemap.xml", "index.xml"])
const files = walk(publicDir)
  .map((p) => rel(publicDir, p))
  .filter((r) => !SKIP.has(r))
if (files.length === 0) {
  console.error("postbuild: public/ is empty; run `quartz build` first")
  process.exit(2)
}

// URL a browser asks for: pages are served without ".html" (html_handling: drop-trailing-slash).
const urlFor = (r) => {
  if (r === "index.html") return "/"
  if (r.endsWith("/index.html")) return "/" + r.slice(0, -"/index.html".length)
  if (r.endsWith(".html")) return "/" + r.slice(0, -".html".length)
  return "/" + r
}
const manifest = files.map((r) => [
  urlFor(r),
  sha(createHash("sha256").update(readFileSync(join(publicDir, r)))).slice(0, 12),
])
const cacheKey = sha(createHash("sha256").update(JSON.stringify(manifest))).slice(0, 10)

const built = new Date().toISOString()
const version = {
  version: content,
  built,
  documents: docs.filter((d) => d.endsWith(".md") && !d.endsWith(".fa.md")).length,
  persian: docs.filter((d) => d.endsWith(".fa.md")).length,
  cache: cacheKey,
}
writeFileSync(join(publicDir, "version.json"), JSON.stringify(version) + "\n")

const urls = ["/version.json", ...manifest.map(([u]) => u)]
const sw = `// Generated by scripts/postbuild.mjs. Do not edit.
const CACHE = ${JSON.stringify("shahrvand-" + cacheKey)}
const FONTS = "shahrvand-fonts"
const PRECACHE = ${JSON.stringify(urls)}

self.addEventListener("install", (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE)
    // A few at a time: ~350 files at once makes a slow connection time out.
    for (let i = 0; i < PRECACHE.length; i += 12) {
      await Promise.all(PRECACHE.slice(i, i + 12).map(async (url) => {
        const res = await fetch(url, { cache: "reload" })
        if (!res.ok) throw new Error("precache " + url + " " + res.status)
        await cache.put(url, res)
      }))
    }
    // First visit: nothing to protect, so take over at once. An update waits for the Update button.
    if (!self.registration.active) await self.skipWaiting()
  })())
})

self.addEventListener("activate", (event) => {
  event.waitUntil((async () => {
    for (const k of await caches.keys()) if (k !== CACHE && k !== FONTS) await caches.delete(k)
    await self.clients.claim()
  })())
})

self.addEventListener("message", (event) => {
  if (event.data && event.data.type === "SKIP_WAITING") self.skipWaiting()
})

self.addEventListener("fetch", (event) => {
  const req = event.request
  if (req.method !== "GET") return
  const url = new URL(req.url)

  // Web fonts come from Google: keep the last copy, refresh in the background.
  if (url.hostname === "fonts.googleapis.com" || url.hostname === "fonts.gstatic.com") {
    event.respondWith((async () => {
      const cache = await caches.open(FONTS)
      const hit = await cache.match(req)
      const fresh = fetch(req).then((res) => { if (res.ok || res.type === "opaque") cache.put(req, res.clone()); return res }).catch(() => hit)
      return hit || fresh
    })())
    return
  }

  if (url.origin !== location.origin) return

  // Account endpoints are live Worker routes, never documents: without this, the navigation to
  // /api/export would be answered with the cached 404 page.
  if (url.pathname.startsWith("/api/") || url.pathname.startsWith("/auth/")) return

  // The documents: the installed copy first, so reading never waits on the network.
  event.respondWith((async () => {
    const hit = await caches.match(url.pathname, { cacheName: CACHE })
    if (hit) return hit
    if (req.mode === "navigate") {
      const miss = await caches.match("/404", { cacheName: CACHE })
      if (miss) return new Response(await miss.blob(), { status: 404, headers: miss.headers })
    }
    return fetch(req)
  })())
})
`
writeFileSync(join(publicDir, "sw.js"), sw)

// The browser must always ask for a fresh sw.js, or it would never notice an update.
writeFileSync(
  join(publicDir, "_headers"),
  "/sw.js\n  Cache-Control: no-cache\n/version.json\n  Cache-Control: no-cache\n",
)

console.log(
  `postbuild: documents ${content} (${version.documents} topics, ${version.persian} in Persian), cache ${cacheKey}, ${urls.length} files precached`,
)
